-- ============================================================================
-- 091 修正 pure_metal 的判定语义
-- ----------------------------------------------------------------------------
-- 090 用 element_at_most(C/Mn/Al/Cr) 定义纯铁，但成分表里未报道的元素
-- 被当成 0，导致大量只写了 "Fe Bal." 的合金被误判为纯金属（46 条）。
-- 091 改用"元素数"判定，并把 element_at_most 的语义收紧为"必须报道且不超过上界"。
-- ============================================================================
UPDATE canon.alloy_family
SET rule = '{"all":[{"base_element":"Fe"},{"n_elements_at_most":1}]}',
    description = '成分表只声明 Fe（Bal.）的纯铁/工业纯铁'
WHERE family_key = 'pure_metal';
